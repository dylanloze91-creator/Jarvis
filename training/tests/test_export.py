"""Partie pure de l'export : réécriture du Modelfile, recherche des outils llama.cpp, garde-fous."""

from __future__ import annotations

from pathlib import Path

import pytest

import export_ollama

FIXTURES = Path(__file__).parent / "fixtures"

# Modelfile de qwen2.5-coder:7b tel que `ollama show --modelfile` le rend. Ollama ne tourne pas dans
# l'environnement de test : la fixture a été reconstituée le 2026-11-02 à partir des blobs publiés sur
# https://ollama.com/library/qwen2.5-coder:7b (template 1e65450c3067, 1,6 kB, avec la ligne « # Tools » ;
# system 66b9ea09bd5b ; licence 832dd9e00a68, tronquée). Pas de blob « params » publié pour ce modèle.
MODELFILE_QWEN = (FIXTURES / "qwen2.5-coder-7b.modelfile").read_text(encoding="utf-8")

MODELFILE_MINIMAL = """# Modelfile generated by "ollama show"
# To build a new Modelfile based on this, replace FROM with:
# FROM qwen2.5-coder:7b

FROM /usr/share/ollama/.ollama/models/blobs/sha256-0000
TEMPLATE \"\"\"{{- if .Messages }}
{{- if or .System .Tools }}<|im_start|>system
# Tools
{{- end }}<|im_start|>assistant
{{ end }}\"\"\"
PARAMETER stop <|endoftext|>
PARAMETER stop <|im_start|>
PARAMETER stop <|im_end|>
SYSTEM You are Qwen, created by Alibaba Cloud. You are a helpful assistant.
LICENSE \"\"\"Apache License
# pas un commentaire : dans le bloc
Version 2.0, January 2004\"\"\"
"""


def bloc(texte: str, instruction: str) -> str:
    """Contenu d'un bloc `INSTRUCTION \"\"\"…\"\"\"`."""
    debut = texte.index(f'{instruction} """') + len(f'{instruction} """')
    return texte[debut : texte.index('"""', debut)]


def test_reecriture_du_vrai_modelfile_garde_le_gabarit_au_caractere_pres(tmp_path: Path):
    gguf = tmp_path / "jarvis-coder-Q4_K_M.gguf"
    assert "\n# Tools\n" in MODELFILE_QWEN
    texte = export_ollama.reecrire_modelfile(MODELFILE_QWEN, gguf)
    assert bloc(texte, "TEMPLATE") == bloc(MODELFILE_QWEN, "TEMPLATE")
    assert bloc(texte, "LICENSE") == bloc(MODELFILE_QWEN, "LICENSE")
    assert "\n# Tools\n" in texte
    assert "<tool_call>" in bloc(texte, "TEMPLATE") and "{{- range .Tools }}" in bloc(texte, "TEMPLATE")
    assert "SYSTEM You are Qwen, created by Alibaba Cloud. You are a helpful assistant." in texte
    lignes = texte.splitlines()
    assert lignes[0] == f"FROM {gguf.resolve().as_posix()}"
    assert sum(1 for l in lignes if l.startswith("FROM")) == 1
    assert "sha256-" not in texte
    assert "Modelfile generated" not in texte and "To build a new Modelfile" not in texte


def test_reecriture_garde_tout_sauf_from(tmp_path: Path):
    gguf = tmp_path / "jarvis-coder-Q4_K_M.gguf"
    texte = export_ollama.reecrire_modelfile(MODELFILE_MINIMAL, gguf)
    lignes = texte.splitlines()
    assert lignes[0] == f"FROM {gguf.resolve().as_posix()}"
    assert sum(1 for l in lignes if l.startswith("FROM")) == 1
    assert "sha256-0000" not in texte
    # Les commentaires hors bloc partent, ceux dans un bloc restent.
    assert "Modelfile generated" not in texte
    assert "\n# Tools\n" in texte and "# pas un commentaire : dans le bloc" in texte
    for attendu in ("TEMPLATE", "PARAMETER stop <|im_end|>", "SYSTEM You are Qwen", "LICENSE", "Version 2.0, January 2004"):
        assert attendu in texte
    assert bloc(texte, "TEMPLATE") == bloc(MODELFILE_MINIMAL, "TEMPLATE")


def test_reecriture_sans_from_ajoute_la_ligne_et_cite_les_espaces(tmp_path: Path):
    gguf = tmp_path / "dossier avec espace" / "m.gguf"
    texte = export_ollama.reecrire_modelfile("PARAMETER num_ctx 4096\n", gguf)
    assert texte.splitlines()[0] == f'FROM "{gguf.resolve().as_posix()}"'
    assert texte.splitlines()[1] == "PARAMETER num_ctx 4096"


def test_recherche_des_outils_llama(tmp_path: Path):
    with pytest.raises(SystemExit, match="convert_hf_to_gguf.py introuvable"):
        export_ollama.trouver_convertisseur(tmp_path)
    sources = tmp_path / f"llama.cpp-{export_ollama.LLAMA_TAG}"
    sources.mkdir()
    (sources / "convert_hf_to_gguf.py").write_text("", encoding="utf-8")
    assert export_ollama.trouver_convertisseur(tmp_path) == sources / "convert_hf_to_gguf.py"

    with pytest.raises(SystemExit, match="llama-quantize introuvable"):
        export_ollama.trouver_quantize(tmp_path / "ailleurs")
    (tmp_path / "bin").mkdir()
    (tmp_path / "bin" / "llama-quantize.exe").write_text("", encoding="utf-8")
    assert export_ollama.trouver_quantize(tmp_path) == tmp_path / "bin" / "llama-quantize.exe"


def test_deja_quantifie():
    assert export_ollama.deja_quantifie(Path("x/jarvis-coder-Q4_K_M.gguf"), "Q4_K_M")
    assert export_ollama.deja_quantifie(Path("x/model.q4_k_m.gguf"), "Q4_K_M")
    assert not export_ollama.deja_quantifie(Path("x/jarvis-coder-f16.gguf"), "Q4_K_M")


def test_un_run_dry_run_est_refuse_a_l_export(tmp_path: Path):
    run = tmp_path / "run"
    (run / "adaptateur").mkdir(parents=True)
    (run / "adaptateur" / "adapter_config.json").write_text('{"base_model_name_or_path": "x"}', encoding="utf-8")
    (run / "bilan.json").write_text('{"dry_run": true}', encoding="utf-8")
    with pytest.raises(SystemExit, match="dry-run"):
        export_ollama.main(["--run", str(run), "--out", str(tmp_path / "export"), "--no-create"])


def test_adaptateur_absent(tmp_path: Path):
    with pytest.raises(SystemExit, match="Adaptateur introuvable"):
        export_ollama.main(["--run", str(tmp_path / "rien"), "--out", str(tmp_path / "export")])
