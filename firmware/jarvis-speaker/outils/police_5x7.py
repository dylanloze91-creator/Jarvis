ACCENTS = ['é','è','ê','à','â','ç','ô','û','ù','î','É','…','°']

def cols(rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    out = []
    for c in range(5):
        v = 0
        for r in range(7):
            if rows[r][c] == '#':
                v |= 1 << r
        out.append(v)
    return out

lines = ['// Généré par outils/police_5x7.py — ne pas modifier à la main.',
         '// Police 5 x 7 dessinée pour l\'écran de l\'enceinte (dessin original, domaine public).',
         '// Un glyphe = 5 colonnes ; bit 0 = ligne du haut.', '#pragma once', '#include <stdint.h>', '',
         '#define FONT_FIRST 0x20', '#define FONT_LAST 0x7E', '#define FONT_ACCENT_FIRST 0x7F',
         f'#define FONT_ACCENT_COUNT {len(ACCENTS)}', '',
         f'static const uint8_t font5x7[{0x7F - 0x20 + len(ACCENTS)}][5] = {{']
missing = []
for code in range(0x20, 0x7F):
    ch = chr(code)
    rows = G.get(ch)
    if rows is None:
        missing.append(ch)
        rows = G['?']
    lines.append('    {' + ', '.join(f'0x{v:02X}' for v in cols(rows)) + f'}}, // {ch!r}')
for i, ch in enumerate(ACCENTS):
    lines.append('    {' + ', '.join(f'0x{v:02X}' for v in cols(G[ch])) + f'}}, // {ch} (0x{0x7F + i:02X})')
lines.append('};')
lines.append('')
lines.append('/** Points de code Unicode des lettres accentuées, dans l\'ordre de la table. */')
lines.append('static const uint16_t font_accents[FONT_ACCENT_COUNT] = {' + ', '.join(f'0x{ord(c):04X}' for c in ACCENTS) + '};')
out = Path(__file__).resolve().parent.parent / 'src' / 'font5x7.h'
out.write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('écrit', out, '— glyphes manquants remplacés par « ? » :', ''.join(missing) or 'aucun')
