import { describe, expect, it } from 'vitest';
import { classifyCommand } from './commandSafety.js';

const SANDBOX = { insideSandbox: true, branch: 'jarvis-dev/20261002-outil-version' };

function expectDenied(commands: string[], context = {}): void {
  for (const command of commands) {
    const result = classifyCommand(command, context);
    expect({ command, level: result.level }).toEqual({ command, level: 'denied' });
    expect(result.runsWithoutAsking).toBe(false);
    expect(result.reasons.length).toBeGreaterThan(0);
  }
}

