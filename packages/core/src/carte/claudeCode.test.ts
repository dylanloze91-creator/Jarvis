import { mkdir, mkdtemp, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { demandesTextes } from './demandes.js';
import { ligneClaudeCode, lireClaudeCode, texteClaudeCode } from './lire.js';

// synthetique-test : aucune phrase réelle.
const TAPE = 'synthetique-test corrige le script python du banc';

function user(content: unknown, extra: Record<string, unknown> = {}): Record<string, unknown> {
  return {
    type: 'user',
    uuid: 'u-synthetique',
    sessionId: 's-synthetique',
    timestamp: '2026-11-12T20:00:00.000Z',
    message: { role: 'user', content },
    ...extra,
  };
}

describe('carte — lignes Claude Code', () => {
  it('garde une phrase tapée', () => {
    expect(ligneClaudeCode(user(TAPE))).toMatchObject({ kind: 'demande', texte: TAPE });
    expect(texteClaudeCode(user([{ type: 'text', text: TAPE }]))?.texte).toBe(TAPE);
  });

  it('écarte les consignes de sous-agent (isSidechain)', () => {
    expect(ligneClaudeCode(user('synthetique-test consigne de Claude', { isSidechain: true }))).toEqual({ kind: 'ecartee' });
    expect(texteClaudeCode(user('synthetique-test consigne de Claude', { isSidechain: true }))).toBeNull();
  });

  it('écarte les résumés de reprise', () => {
    expect(ligneClaudeCode(user('synthetique-test résumé', { isCompactSummary: true }))).toEqual({ kind: 'ecartee' });
    expect(
      ligneClaudeCode(user('This session is being continued from a previous conversation that ran out of context. synthetique-test')),
    ).toEqual({ kind: 'ecartee' });
  });

  it("écarte les blocs ajoutés par l'outil", () => {
    for (const texte of [
      '<system-reminder>synthetique-test rappel</system-reminder>',
      '<command-name>/synthetique</command-name>',
      '<command-message>synthetique-test</command-message>',
      '<local-command-stdout>synthetique-test</local-command-stdout>',
      '<local-command-stderr>synthetique-test</local-command-stderr>',
      '<task-notification>synthetique-test</task-notification>',
      'Caveat: The messages below were generated by the user while running local commands. synthetique-test',
    ]) {
      expect(ligneClaudeCode(user(texte))).toEqual({ kind: 'ecartee' });
    }
  });

  it("retire un rappel ajouté à l'intérieur d'un message tapé", () => {
    const ligne = ligneClaudeCode(
      user([
        { type: 'text', text: '<system-reminder>synthetique-test contexte injecté</system-reminder>' },
        { type: 'text', text: TAPE },
      ]),
    );
    expect(ligne).toMatchObject({ kind: 'demande', texte: TAPE });
  });

  it("compte « [Request interrupted by user] » comme une interruption, pas comme une demande", () => {
    expect(ligneClaudeCode(user('[Request interrupted by user]'))).toMatchObject({ kind: 'interruption' });
    expect(ligneClaudeCode(user([{ type: 'text', text: '[Request interrupted by user for tool use]' }]))).toMatchObject({
      kind: 'interruption',
    });
    const demandes = demandesTextes({
      source: 'claude-code',
      conversationId: 's-synthetique',
      messages: [
        { id: 'a', at: null, texte: TAPE },
        { id: 'b', at: null, texte: '', interruption: true },
      ],
    });
    expect(demandes).toHaveLength(1);
    expect(demandes[0]?.rate).toBe(true);
  });

  it("un résultat d'outil seul n'est ni une demande ni une ligne écartée", () => {
    expect(ligneClaudeCode(user([{ type: 'tool_result', content: 'synthetique-test' }]))).toBeNull();
  });

  it('écarte tout le dossier « subagents » et dit combien de lignes', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'carte-cc-'));
    await mkdir(join(dir, 'projet', 'session', 'subagents'), { recursive: true });
    await writeFile(
      join(dir, 'projet', 'session.jsonl'),
      [
        JSON.stringify(user(TAPE)),
        JSON.stringify(user('synthetique-test consigne', { isSidechain: true })),
        JSON.stringify(user('<command-name>/synthetique</command-name>')),
        JSON.stringify(user('[Request interrupted by user]')),
        JSON.stringify({ type: 'assistant', message: { content: 'synthetique-test réponse' } }),
      ].join('\n'),
      'utf8',
    );
    await writeFile(
      join(dir, 'projet', 'session', 'subagents', 'agent-synthetique.jsonl'),
      [JSON.stringify(user('synthetique-test consigne écrite par Claude')), JSON.stringify(user('synthetique-test autre'))].join('\n'),
      'utf8',
    );
    const lu = await lireClaudeCode(dir);
    expect(lu.fichiers).toBe(2);
    expect(lu.ecartees).toBe(4);
    const textes = lu.sessions.flatMap((session) => session.messages.filter((m) => !m.interruption).map((m) => m.texte));
    expect(textes).toEqual([TAPE]);
    const interruptions = lu.sessions.flatMap((session) => session.messages.filter((m) => m.interruption));
    expect(interruptions).toHaveLength(1);
  });
});
