/**
 * Atelier 3D : lire ce qu'OrcaSlicer a écrit dans le G-code (temps, filament, réglages utilisés).
 *
 * Règle du cahier : le temps et le filament dits à l'utilisateur viennent **du fichier produit**,
 * jamais d'une estimation faite à la main. Une valeur absente reste absente (`null`), et
 * `lireGcode` le dit : Jarvis ne doit alors rien annoncer.
 *
 * Commentaires relevés sur OrcaSlicer 2.4.2 (23 novembre 2026) :
 *   ; estimated printing time (normal mode) = 16m 59s
 *   ; filament used [mm] = 1403.18
 *   ; filament used [g] = 4.29
 *   ; total layers count = 100
 *   ; curr_bed_type = Cool Plate
 *   EXCLUDE_OBJECT_DEFINE NAME=cube.stl_id_0_copy_0 …
 *
 * Pur : reçoit le texte du fichier.
 */

export interface InfosGcode {
  /** Durée estimée en secondes (mode normal). */
  secondes: number | null;
  /** Le texte tel qu'OrcaSlicer l'a écrit (« 16m 59s »). */
  dureeTexte: string | null;
  filamentMm: number | null;
  filamentG: number | null;
  filamentCm3: number | null;
  couches: number | null;
  hauteurMax: number | null;
  trancheur: string | null;
  plateau: string | null;
  imprimante: string | null;
  reglage: string | null;
  filament: string | null;
  saveur: string | null;
  buse: number | null;
  lit: number | null;
  /** Noms des objets déclarés pour Klipper (`[exclude_object]`). */
  objets: string[];
}

function valeur(texte: string, cle: string): string | null {
  const echappee = cle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`^;\\s*${echappee}\\s*[=:]\\s*(.+?)\\s*$`, 'm').exec(texte);
  return m ? m[1]!.replace(/^"(.*)"$/, '$1') : null;
}

function nombre(texte: string | null): number | null {
  if (texte === null) return null;
  const n = Number(texte.split(/[,;]/)[0]);
  return Number.isFinite(n) ? n : null;
}

/** « 1d 2h 3m 4s », « 16m 59s », « 45s » → secondes. Rend `null` si le texte ne se lit pas. */
export function dureeEnSecondes(texte: string): number | null {
  const parties = [...texte.matchAll(/(\d+(?:\.\d+)?)\s*([dhms])/g)];
  if (parties.length === 0) return null;
  const reste = texte.replace(/(\d+(?:\.\d+)?)\s*([dhms])/g, '').trim();
  if (reste) return null;
  const facteur = { d: 86400, h: 3600, m: 60, s: 1 } as const;
  return Math.round(parties.reduce((s, p) => s + Number(p[1]) * facteur[p[2] as keyof typeof facteur], 0));
}

export function lireGcode(texte: string): InfosGcode {
  const duree = valeur(texte, 'estimated printing time (normal mode)');
  const generePar = /^;\s*generated by\s+(.+?)\s+on\s/m.exec(texte);
  const objets = [...texte.matchAll(/^EXCLUDE_OBJECT_DEFINE\s+NAME=(\S+)/gm)].map((m) => m[1]!);
  const debut = /^PRINT_START\b.*?\bEXTRUDER=(\d+(?:\.\d+)?).*?\bBED=(\d+(?:\.\d+)?)/m.exec(texte);
  return {
    secondes: duree ? dureeEnSecondes(duree) : null,
    dureeTexte: duree,
    filamentMm: nombre(valeur(texte, 'filament used [mm]')),
    filamentG: nombre(valeur(texte, 'total filament used [g]') ?? valeur(texte, 'filament used [g]')),
    filamentCm3: nombre(valeur(texte, 'filament used [cm3]')),
    couches: nombre(valeur(texte, 'total layers count') ?? valeur(texte, 'total layer number')),
    hauteurMax: nombre(valeur(texte, 'max_z_height')),
    trancheur: generePar ? generePar[1]! : null,
    plateau: valeur(texte, 'curr_bed_type'),
    imprimante: valeur(texte, 'printer_settings_id'),
    reglage: valeur(texte, 'print_settings_id'),
    filament: valeur(texte, 'filament_settings_id'),
    saveur: valeur(texte, 'gcode_flavor'),
    buse: debut ? Number(debut[1]) : nombre(valeur(texte, 'nozzle_temperature_initial_layer')),
    lit: debut ? Number(debut[2]) : null,
    objets,
  };
}

/** « 1 h 05 », « 17 min » : durée dite à l'utilisateur. */
export function dureeParlee(secondes: number): string {
  const min = Math.max(1, Math.round(secondes / 60));
  if (min < 60) return `${min} min`;
  const h = Math.floor(min / 60);
  const reste = min % 60;
  return reste ? `${h} h ${String(reste).padStart(2, '0')}` : `${h} h`;
}

/**
 * Phrase du temps et du filament, seulement si les deux sont dans le fichier :
 * « Environ 17 min et 4,3 g de filament (1,40 m). » ; sinon `null` (on ne devine pas).
 */
export function phraseTempsFilament(infos: InfosGcode): string | null {
  if (infos.secondes === null || infos.filamentG === null) return null;
  const g = String(Math.round(infos.filamentG * 10) / 10).replace('.', ',');
  const metres = infos.filamentMm !== null ? ` (${(infos.filamentMm / 1000).toFixed(2).replace('.', ',')} m)` : '';
  return `Environ ${dureeParlee(infos.secondes)} et ${g} g de filament${metres}.`;
}
