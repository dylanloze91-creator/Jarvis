import { describe, expect, it } from 'vitest';
import { analyserStl, ecartsDeCotes } from './stl.js';
import { dureeEnSecondes, dureeParlee, lireGcode, phraseTempsFilament } from './gcode.js';

type V = [number, number, number];

function cube(o: V = [0, 0, 0], s = 20): V[][] {
  const v: V[] = [
    [0, 0, 0], [s, 0, 0], [s, s, 0], [0, s, 0],
    [0, 0, s], [s, 0, s], [s, s, s], [0, s, s],
  ].map((p) => [p[0]! + o[0], p[1]! + o[1], p[2]! + o[2]] as V);
  const f = [[0, 2, 1], [0, 3, 2], [4, 5, 6], [4, 6, 7], [0, 1, 5], [0, 5, 4], [1, 2, 6], [1, 6, 5], [2, 3, 7], [2, 7, 6], [3, 0, 4], [3, 4, 7]];
  return f.map((t) => t.map((i) => v[i]!));
}

function ascii(tris: V[][]): Uint8Array {
  let s = 'solid t\n';
  for (const t of tris) s += `facet normal 0 0 0\nouter loop\n${t.map((p) => `vertex ${p.join(' ')}`).join('\n')}\nendloop\nendfacet\n`;
  return new TextEncoder().encode(s + 'endsolid t\n');
}

function binaire(tris: V[][]): Uint8Array {
  const buf = new ArrayBuffer(84 + tris.length * 50);
  const vue = new DataView(buf);
  vue.setUint32(80, tris.length, true);
  tris.forEach((t, i) => t.forEach((p, k) => p.forEach((x, j) => vue.setFloat32(84 + i * 50 + 12 + k * 12 + j * 4, x, true))));
  return new Uint8Array(buf);
}

describe('relecture du STL', () => {
  it('un cube fermé, en ASCII comme en binaire : fermé, cotes et volume justes', () => {
    for (const octets of [ascii(cube()), binaire(cube())]) {
      const a = analyserStl(octets);
      expect(a.fermee).toBe(true);
      expect(a.triangles).toBe(12);
      expect(a.taille).toEqual([20, 20, 20]);
      expect(a.volume).toBeCloseTo(8000, 3);
    }
    expect(analyserStl(binaire(cube())).format).toBe('binaire');
    expect(analyserStl(ascii(cube())).format).toBe('ascii');
  });

  it('un triangle en moins : arêtes libres, pas fermé', () => {
    const a = analyserStl(ascii(cube().slice(1)));
    expect(a.fermee).toBe(false);
    expect(a.aretesLibres).toBe(3);
  });

  it('un triangle retourné : mal orienté, pas fermé', () => {
    const tris = cube();
    tris[0] = [tris[0]![0]!, tris[0]![2]!, tris[0]![1]!];
    const a = analyserStl(ascii(tris));
    expect(a.fermee).toBe(false);
    expect(a.aretesMalOrientees).toBeGreaterThan(0);
  });

  it('deux cubes qui se touchent par une arête : arête portée par quatre triangles, pas fermé', () => {
    const a = analyserStl(ascii([...cube(), ...cube([20, 20, 0])]));
    expect(a.aretesMultiples).toBe(1);
    expect(a.fermee).toBe(false);
  });

  it('fichier vide ou coupé : erreur dite, jamais « fermé »', () => {
    expect(() => analyserStl(new Uint8Array())).toThrow(/vide/);
    expect(() => analyserStl(new TextEncoder().encode('solid x\nvertex 0 0 0\nvertex 1 0 0\n'))).toThrow(/incomplet/);
  });

  it('écarts de cotes à 0,2 mm près', () => {
    expect(ecartsDeCotes([80, 50, 30.1], [80, 50, 30])).toEqual([]);
    expect(ecartsDeCotes([80, 50, 25], [80, 50, 30])).toEqual(['Z : 25 mm mesurés pour 30 mm attendus.']);
  });
});

// Extrait d'un vrai fichier d'OrcaSlicer 2.4.2 (cube de 20 mm tranché le 23 novembre 2026).
const GCODE = `; HEADER_BLOCK_START
; generated by OrcaSlicer 2.4.2 on 2026-11-23 at 12:31:32
; total layer number: 100
; filament_density: 1.27
; filament_diameter: 1.75
; max_z_height: 20.00
; filament: 1
; HEADER_BLOCK_END
EXCLUDE_OBJECT_DEFINE NAME=cube.stl_id_0_copy_0 CENTER=125,125 POLYGON=[[115,115],[135,115],[135,135],[115,135],[115,115]]
PRINT_START EXTRUDER=245 BED=60
G1 X10 Y10
; filament used [mm] = 1403.18
; filament used [cm3] = 3.38
; filament used [g] = 4.29
; filament cost = 0.13
; total filament used [g] = 4.29
; total layers count = 100
; estimated printing time (normal mode) = 16m 59s
; estimated first layer printing time (normal mode) = 16s
; curr_bed_type = Cool Plate
; filament_settings_id = "Generic PETG @System - Copie"
; gcode_flavor = klipper
; print_settings_id = 0.20mm Standard @MyKlipper - Copie
; printer_settings_id = MyKlipper 0.4 nozzle - Copie
`;

describe('lecture du G-code d’OrcaSlicer', () => {
  it('temps, filament et réglages lus dans le fichier', () => {
    const g = lireGcode(GCODE);
    expect(g.secondes).toBe(16 * 60 + 59);
    expect(g.dureeTexte).toBe('16m 59s');
    expect(g.filamentMm).toBe(1403.18);
    expect(g.filamentG).toBe(4.29);
    expect(g.filamentCm3).toBe(3.38);
    expect(g.couches).toBe(100);
    expect(g.hauteurMax).toBe(20);
    expect(g.trancheur).toBe('OrcaSlicer 2.4.2');
    expect(g.plateau).toBe('Cool Plate');
    expect(g.imprimante).toBe('MyKlipper 0.4 nozzle - Copie');
    expect(g.reglage).toBe('0.20mm Standard @MyKlipper - Copie');
    expect(g.filament).toBe('Generic PETG @System - Copie');
    expect(g.saveur).toBe('klipper');
    expect(g.buse).toBe(245);
    expect(g.lit).toBe(60);
    expect(g.objets).toEqual(['cube.stl_id_0_copy_0']);
    expect(phraseTempsFilament(g)).toBe('Environ 17 min et 4,3 g de filament (1,40 m).');
  });

  it('la première couche n’est pas prise pour le temps total', () => {
    const g = lireGcode('; estimated first layer printing time (normal mode) = 16s\n; filament used [g] = 1\n');
    expect(g.secondes).toBeNull();
    expect(phraseTempsFilament(g)).toBeNull();
  });

  it('rien d’inventé quand le fichier ne dit rien', () => {
    const g = lireGcode('G28\nG1 X0\n');
    expect(g.secondes).toBeNull();
    expect(g.filamentG).toBeNull();
    expect(g.objets).toEqual([]);
    expect(phraseTempsFilament(g)).toBeNull();
  });

  it('durées', () => {
    expect(dureeEnSecondes('1d 2h 3m 4s')).toBe(93784);
    expect(dureeEnSecondes('45s')).toBe(45);
    expect(dureeEnSecondes('bientôt')).toBeNull();
    expect(dureeParlee(20)).toBe('1 min');
    expect(dureeParlee(3900)).toBe('1 h 05');
    expect(dureeParlee(7200)).toBe('2 h');
  });
});
